package ru.friends.customjukebox.data;

import com.google.gson.Gson;
import com.google.gson.JsonArray;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import net.minecraft.resource.Resource;
import net.minecraft.resource.ResourceManager;
import net.minecraft.util.Identifier;
import ru.friends.customjukebox.CustomJukebox;

import java.io.IOException;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.Optional;

/**
 * Loads assets/customjukebox/tracks.json.
 *
 * tracks.json format (array, ORDER MATTERS - it's the order shown in the
 * GUI and it's generated by tools/generate_tracks.py from your album
 * list):
 *
 * [
 *   {
 *     "artist": "cupsize",
 *     "album": "заставь меня плакать",
 *     "tracks": [
 *       { "id": "disc_01", "title": "Track title" },
 *       { "id": "disc_02", "title": "Another title" }
 *     ]
 *   },
 *   ...
 * ]
 *
 * Every object in the top-level array becomes its own separate group in
 * the GUI, even if "artist"+"album" repeats a previous entry verbatim -
 * we never merge groups back together.
 *
 * Cover texture for track "id" is expected at
 *   assets/customjukebox/textures/covers/{id}.png
 * Sound event for track "id" is expected to be registered in sounds.json
 * under the key "track.{id}" (tools/generate_tracks.py does this for you).
 */
public final class TrackLibrary {
    private static final Identifier TRACKS_JSON = Identifier.of(CustomJukebox.MOD_ID, "tracks.json");
    private static final Gson GSON = new Gson();

    private static List<Album> albums = List.of();

    private TrackLibrary() {}

    public static List<Album> getAlbums() {
        return albums;
    }

    public static Optional<Track> findTrack(String trackId) {
        for (Album album : albums) {
            for (Track track : album.tracks()) {
                if (track.id().equals(trackId)) {
                    return Optional.of(track);
                }
            }
        }
        return Optional.empty();
    }

    /** Case-insensitive search across title / album / artist. Preserves group order/separation. */
    public static List<Album> search(String query) {
        if (query == null || query.isBlank()) {
            return albums;
        }
        String needle = query.toLowerCase(Locale.ROOT).trim();
        List<Album> result = new ArrayList<>();
        for (Album album : albums) {
            boolean albumMatches = album.title().toLowerCase(Locale.ROOT).contains(needle)
                    || album.artist().toLowerCase(Locale.ROOT).contains(needle);

            List<Track> matchingTracks = new ArrayList<>();
            for (Track track : album.tracks()) {
                if (albumMatches
                        || track.title().toLowerCase(Locale.ROOT).contains(needle)) {
                    matchingTracks.add(track);
                }
            }
            if (!matchingTracks.isEmpty()) {
                result.add(new Album(album.artist(), album.title(), matchingTracks));
            }
        }
        return result;
    }

    public static void reload(ResourceManager manager) {
        List<Album> loaded = new ArrayList<>();
        try {
            Optional<Resource> resource = manager.getResource(TRACKS_JSON);
            if (resource.isEmpty()) {
                CustomJukebox.LOGGER.warn("[CustomJukebox] tracks.json not found at assets/customjukebox/tracks.json - playlist will be empty.");
                albums = List.of();
                return;
            }

            try (InputStreamReader reader = new InputStreamReader(resource.get().getInputStream(), StandardCharsets.UTF_8)) {
                JsonArray root = JsonParser.parseReader(reader).getAsJsonArray();
                for (int i = 0; i < root.size(); i++) {
                    JsonObject albumObj = root.get(i).getAsJsonObject();
                    String artist = albumObj.get("artist").getAsString();
                    String title = albumObj.get("album").getAsString();

                    List<Track> tracks = new ArrayList<>();
                    JsonArray tracksArr = albumObj.getAsJsonArray("tracks");
                    for (int j = 0; j < tracksArr.size(); j++) {
                        JsonObject t = tracksArr.get(j).getAsJsonObject();
                        String id = t.get("id").getAsString();
                        String trackTitle = t.has("title") ? t.get("title").getAsString() : id;

                        Identifier cover = Identifier.of(CustomJukebox.MOD_ID, "textures/covers/" + id + ".png");
                        Identifier soundId = Identifier.of(CustomJukebox.MOD_ID, "track." + id);

                        tracks.add(new Track(id, artist, title, trackTitle, cover, soundId));
                    }
                    loaded.add(new Album(artist, title, tracks));
                }
            }
        } catch (IOException | RuntimeException e) {
            CustomJukebox.LOGGER.error("[CustomJukebox] Failed to load tracks.json", e);
            loaded = List.of();
        }

        albums = loaded;
        CustomJukebox.LOGGER.info("[CustomJukebox] Loaded {} album groups from tracks.json", albums.size());
    }
}